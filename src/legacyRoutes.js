const UPLOAD_PREFIX = 'wp-upload:';

/**
 * Returns a Response for legacy URLs, or null to continue normal routing.
 * Only GET/HEAD are considered.
 */
export async function handleLegacy(request, env, url) {
  if (request.method !== 'GET' && request.method !== 'HEAD') return null;
  const path = url.pathname.replace(/\/+$/, '') || '/';
  const to = (p) => Response.redirect(new URL(p, url.origin).toString(), 301);

  if (PAGE_MAP[path]) return to(PAGE_MAP[path]);
  if (path.startsWith('/wp-content/uploads/')) {
    const key = UPLOAD_PREFIX + path.slice('/wp-content/uploads/'.length);
    const { value, metadata } = await env.IMA_KARATE.getWithMetadata(key, { type: 'arrayBuffer' });
    if (!value) return new Response('Not found', { status: 404 });
    return new Response(request.method === 'HEAD' ? null : value, {
      headers: { 'Content-Type': metadata?.contentType || 'application/octet-stream', 'Cache-Control': 'public, max-age=86400' },
    });
  }
  if (path.startsWith('/category/') || path.startsWith('/author/') || path === '/feed' || path.endsWith('/feed')) return to('/news-events');
  if (/^\/wp-(admin|login\.php|json|includes|content)(\/|$)/.test(path) || path === '/xmlrpc.php' || path.startsWith('/wp-sitemap')) {
    return new Response('Not found', { status: 404 });
  }
  const slug = path.slice(1);
  if (slug && !slug.includes('/') && OLD_POSTS.has(slug)) return to('/news-events');
  return null;
}
